type Params = unknown[];
export type RunResult = { changes: number; lastInsertRowid: number };

const g = globalThis as unknown as { __handoverPool?: Pool; __handoverReady?: Promise<void> };
const txStore = new AsyncLocalStorage<PoolClient>();

function pool(): Pool {
  if (!g.__handoverPool) {
    g.__handoverPool = new Pool({
      connectionString: process.env.DATABASE_URL || DEFAULT_URL,
      max: Number(process.env.PG_POOL_MAX || 10),
      idleTimeoutMillis: 30_000,
      connectionTimeoutMillis: 10_000,
      statement_timeout: Number(process.env.PG_STATEMENT_TIMEOUT_MS || 15_000),
    });
    g.__handoverPool.on("error", (e) => console.error("[db] idle client error", e.message));
  }
  return g.__handoverPool;
}

/** Create or upgrade the schema. An advisory lock makes this safe when many instances start at once. */
async function migrate() {
  fs.mkdirSync(UPLOAD_DIR, { recursive: true });
  fs.mkdirSync(CACHE_DIR, { recursive: true });
  const c = await pool().connect();
  try {
    await c.query("SELECT pg_advisory_lock(727274)");
    await c.query("CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())");
    const { rows } = await c.query<{ v: number | null }>("SELECT max(version) AS v FROM schema_migrations");
    const current = rows[0]?.v ?? 0;
    for (let i = current; i < MIGRATIONS.length; i++) {
      await c.query("BEGIN");
      try {
        await c.query(MIGRATIONS[i]);
        await c.query("INSERT INTO schema_migrations (version) VALUES ($1)", [i + 1]);
        await c.query("COMMIT");
      } catch (e) {
        await c.query("ROLLBACK");
        throw e;
      }
    }
  } finally {
    await c.query("SELECT pg_advisory_unlock(727274)").catch(() => {});
    c.release();
  }
}

function ready(): Promise<void> {
  if (!g.__handoverReady) {
    g.__handoverReady = migrate().catch((e) => {
      g.__handoverReady = undefined; // retry on the next query
      throw e;
    });
  }
  return g.__handoverReady;
}

/** Turn SQLite-style `?` placeholders into `$1, $2, ...`, skipping quoted text. */
export function toPg(sql: string): string {
  let out = "";
  let n = 0;
  let quote: string | null = null;
  for (const ch of sql) {
    if (quote) {
      if (ch === quote) quote = null;
      out += ch;
    } else if (ch === "'" || ch === '"') {
      quote = ch;
      out += ch;
    } else if (ch === "?") {
      out += `$${++n}`;
    } else out += ch;
  }
  return out;
}

async function query(sql: string, params: Params) {
  await ready();
  const text = toPg(sql);
  const values = params.map((p) => (typeof p === "boolean" ? (p ? 1 : 0) : p));
  const client = txStore.getStore();
  return client ? client.query(text, values) : pool().query(text, values);
}

function withReturning(sql: string): string {
  const m = /^\s*INSERT\s+INTO\s+(\w+)/i.exec(sql);
  if (!m || !ID_TABLES.has(m[1].toLowerCase()) || /\bRETURNING\b/i.test(sql)) return sql;
  return `${sql.trimEnd().replace(/;$/, "")} RETURNING id`;
}

export type Statement = {
  get(...params: Params): Promise<unknown>;
  all(...params: Params): Promise<unknown[]>;
  run(...params: Params): Promise<RunResult>;
};

export type Db = {
  prepare(sql: string): Statement;
  get(sql: string, ...params: Params): Promise<unknown>;
  all(sql: string, ...params: Params): Promise<unknown[]>;
  run(sql: string, ...params: Params): Promise<RunResult>;
  exec(sql: string): Promise<void>;
};

const api: Db = {
  prepare: (sql) => ({
    get: async (...p) => await api.get(sql, ...p),
    all: async (...p) => await api.all(sql, ...p),
    run: async (...p) => await api.run(sql, ...p),
  }),
  async get(sql, ...p) {
    const r = await query(sql, p);
    return r.rows[0];
  },
  async all(sql, ...p) {
    return (await query(sql, p)).rows;
  },
  async run(sql, ...p) {
    const r = await query(withReturning(sql), p);
    const id = r.rows[0] && typeof r.rows[0].id === "number" ? (r.rows[0].id as number) : 0;
    return { changes: r.rowCount ?? 0, lastInsertRowid: id };
  },
  async exec(sql) {
    await ready();
    const client = txStore.getStore();
    await (client ?? pool()).query(sql);
  },
};

export function db(): Db {
  return api;
}

/**
 * Run `fn` in one transaction. Every db() call made inside it (even in other modules) uses the same connection.
 * Nested calls join the outer transaction.
 */
export async function tx<T>(fn: () => Promise<T>): Promise<T> {
  if (txStore.getStore()) return fn();
  await ready();
  const client = await pool().connect();
  try {
    await client.query("BEGIN");
    const out = await txStore.run(client, fn);
    await client.query("COMMIT");
    return out;
  } catch (e) {
    await client.query("ROLLBACK").catch(() => {});
    throw e;
  } finally {
    client.release();
  }
}

/** Cheap connectivity check for /api/health. */
export async function ping(): Promise<boolean> {
  await ready();
  await pool().query("SELECT 1");
  return true;
}

export const now = () => new Date().toISOString();
